"""Write the generated Lean data files from data/tables.json (made by extract.py).

Output: ArTax/Data/Ipc.lean, ArTax/Data/Ganancias.lean, ArTax/Data/Jubilados.lean, ArTax/Data/Monotributo.lean,
ArTax/Data/Sociedades.lean. Every number in them is a
figure printed by ARCA or INDEC; nothing is computed here.
"""
import json, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
HEAD = '/-! Generated by tools/gen_lean.py from data/tables.json. Do not edit by hand. -/\n\n'
SCALES = [('2025-S1', 's2025S1'), ('2025-S2', 's2025S2'), ('2025', 's2025'),
          ('2026-S1', 's2026S1'), ('2026-S2', 's2026S2'), ('2026', 's2026')]
DED_KEYS = ['mni', 'conyuge', 'hijo', 'hijoIncapacitado', 'especial1', 'especial1Nuevos', 'especial2']
MONO_KEYS = ['ingresos', 'alquileres', 'precioUnitario', 'impServicios', 'impVenta', 'sipa', 'obraSocial',
             'totalServicios', 'totalVenta']
MONO = [('2025-02', 't202502'), ('2025-08', 't202508'), ('2026-02', 't202602'), ('2026-08', 't202608')]


def scale(rows):
    return '[' + ', '.join(f'⟨{lo}, {fixed}, {rate}⟩' for lo, _hi, fixed, rate in rows) + ']'


def ipc_lean(ipc):
    arms = '\n'.join(f'  | {k.replace("-", "")} => {v}' for k, v in sorted(ipc.items()))
    return (HEAD + 'namespace ArTax\n\n'
            '/-- INDEC, Índice de Precios al Consumidor, nivel general, total nacional, base December 2016 = 100:\n'
            'the index of month YYYYMM times 10 000 (the series has four decimals). Zero for a month not in the series. -/\n'
            'def ipc : Nat → Int\n' + arms + '\n  | _ => 0\n\n'
            f'/-- The first and the last month of the series. -/\ndef ipcFirst : Nat := {min(ipc).replace("-", "")}\n'
            f'def ipcLast : Nat := {max(ipc).replace("-", "")}\n\nend ArTax\n')


def ganancias_lean(d):
    out = ['import ArTax.Ganancias.Basic\n\n' + HEAD + 'namespace ArTax.Ganancias\n']
    for key, name in SCALES:
        ded = d['art30'][key]
        out.append(f'/-- ARCA, deducciones del art. 30, {key} (centavos). -/\ndef d{name[1:]} : Deductions :=\n  ⟨'
                   + ', '.join(str(ded[k]) for k in DED_KEYS) + '⟩\n')
        tabs = d['art94'][key]
        out.append(f'/-- ARCA, escala del art. 94, {key}: the headline table. -/\ndef {name} : Scale :=\n  {scale(tabs[0])}\n')
        if len(tabs) > 1:
            out.append(f'/-- ARCA, escala del art. 94, {key}: the cumulative table of each month, January first. -/\n'
                       f'def m{name[1:]} : List Scale := [\n  ' + ',\n  '.join(scale(t) for t in tabs[1:]) + ']\n')
    out.append('end ArTax.Ganancias\n')
    return '\n'.join(out)


def monotributo_lean(mono):
    out = ['import ArTax.Monotributo.Basic\n\n' + HEAD + 'namespace ArTax.Monotributo\n']
    for key, name in MONO:
        rows = ',\n  '.join('⟨' + ', '.join(str(mono[key][c][k]) for k in MONO_KEYS) + '⟩' for c in 'ABCDEFGHIJK')
        out.append(f'/-- ARCA, cuadro de categorías vigente desde {key}: categories A to K (centavos). -/\n'
                   f'def {name} : Table := [\n  {rows}]\n')
    out.append('end ArTax.Monotributo\n')
    return '\n'.join(out)


def jubilados_lean(jub):
    out = ['import ArTax.Ganancias.Basic\n\n' + HEAD + 'namespace ArTax.Ganancias\n\n'
           '/-- One month of ARCA\'s table of the specific deduction for pensions: the haber mínimo garantizado, eight\n'
           'times it as printed, and the running total as printed (centavos). -/\n'
           'structure Haber where\n  hmg : Int\n  producto : Int\n  acumulado : Int\nderiving Repr, DecidableEq\n']
    for year, rows in sorted(jub.items()):
        body = ',\n  '.join(f'⟨{r["hmg"]}, {r["producto"]}, {r["acumulado"]}⟩' for r in rows)
        res = ', '.join(r['resolucion'] for r in rows)
        out.append(f'/-- ARCA, deducción específica {year}, January first (ANSES resolutions {res}). -/\n'
                   f'def h{year} : List Haber := [\n  {body}]\n')
    out.append('end ArTax.Ganancias\n')
    return '\n'.join(out)


def sociedades_lean(art73):
    out = ['import ArTax.Scale\n\n' + HEAD + 'namespace ArTax.Sociedades\n']
    for year, rows in sorted(art73.items()):
        out.append(f'/-- ARCA, escala del art. 73 for fiscal years starting from 1 January {year}. -/\n'
                   f'def arca{year} : Scale := {scale(rows)}\n')
    out.append('end ArTax.Sociedades\n')
    return '\n'.join(out)


def main():
    d = json.loads((ROOT / 'data' / 'tables.json').read_text(encoding='utf-8'))
    data = ROOT / 'ArTax' / 'Data'
    data.mkdir(exist_ok=True)
    for name, text in [('Ipc.lean', ipc_lean(d['ipc'])), ('Ganancias.lean', ganancias_lean(d)),
                       ('Jubilados.lean', jubilados_lean(d['jubilados'])),
                       ('Sociedades.lean', sociedades_lean(d['art73'])),
                       ('Monotributo.lean', monotributo_lean(d['monotributo']))]:
        (data / name).write_text(text, encoding='utf-8', newline='\n')
    print('wrote', [p.name for p in sorted(data.iterdir())])


if __name__ == '__main__':
    main()
